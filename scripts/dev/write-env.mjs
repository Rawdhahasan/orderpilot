// Writes .env.local (git-ignored) for the local Supabase stack. Values are
// never printed. Your own AI settings (AI_* and GEMINI_* lines, including
// GEMINI_API_KEY) are kept when the file is regenerated.
// Usage: corepack pnpm db:env
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { localStatus } from "./local-supabase.mjs";

const target = new URL("../../.env.local", import.meta.url);
const kept = existsSync(target)
  ? readFileSync(target, "utf8")
      .split("\n")
      .filter((line) => /^(AI_|GEMINI_)[A-Z0-9_]*=/.test(line))
  : [];
const status = localStatus();
const lines = [
  "# Generated by corepack pnpm db:env for the LOCAL Supabase stack only. Do not commit.",
  `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}`,
  `SUPABASE_SECRET_KEY=${status.SECRET_KEY}`,
  "APP_BASE_URL=http://localhost:3000",
  "MAIL_TRANSPORT=mailpit",
  `MAILPIT_URL=${status.MAILPIT_URL ?? status.INBUCKET_URL ?? "http://127.0.0.1:54324"}`,
  `INTERNAL_JOB_SECRET=${randomBytes(32).toString("hex")}`,
  "DEPLOYMENT_ENV=local",
  ...(kept.some((line) => line.startsWith("AI_EXTRACTION_PROVIDER="))
    ? []
    : ["AI_EXTRACTION_PROVIDER=simulated"]),
  ...kept,
  "",
];
writeFileSync(target, lines.join("\n"), { mode: 0o600 });
console.log(
  kept.length
    ? `Wrote .env.local for the local Supabase stack (kept ${kept.length} AI setting(s)).`
    : "Wrote .env.local for the local Supabase stack.",
);
